export const BANNED_WORD_STEMS: readonly string[] = [
  "fuck",
  "shit",
  "bitch",
  "cunt",
  "nigger",
  "faggot",
  "rape",
];

export function containsBannedWord(normalizedValue: string): boolean {
  return BANNED_WORD_STEMS.some((stem) => normalizedValue.includes(stem));
}
